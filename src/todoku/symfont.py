# 書体ごとの、印のついた箱・印のない箱の番号（チェックを入れる・外すときに書く字。対応表の字の名前から：
# Wingdings 0xFE BALLOT BOX WITH BOLD CHECK・0xA8 LIGHT WHITE SQUARE、Wingdings 2 0x52 BALLOT BOX WITH CHECK・0xA3 WHITE SQUARE。
# 印のついた箱の字のない書体は、塗った四角：Webdings 0x67 BLACK LARGE SQUARE・0x63 WHITE LARGE SQUARE、
# Zapf Dingbats 0x6E BLACK SQUARE・0x6F LOWER RIGHT DROP-SHADOWED WHITE SQUARE）
_BOX_CODES = {id(_WINGDINGS): (0xFE, 0xA8), id(_WINGDINGS_2): (0x52, 0xA3), id(_WEBDINGS): (0x67, 0x63),
              id(_ZAPF_DINGBATS): (0x6E, 0x6F)}
_TABLES: dict[int, tuple] = {}
_UNKNOWN = ("", (None,) * 0xE0)  # 記号の書体と宣言された、対応表のない書体：どの番号の字も決めない


@functools.lru_cache(maxsize=4096)
def key(font: str | None) -> str:
    """書体の名前を比べる形（小文字・空白 1 つ）。文書が「記号の書体」と宣言した書体の名前の集まり（symbols）も、この形で持つ。"""
    return " ".join((font or "").lower().split())


def _table(font: str | None, symbols=()):
    k = key(font)
    raw = _NAMES.get(k)
    if raw is None:
        return _UNKNOWN if k and k in symbols else None
    t = _TABLES.get(id(raw))
    if t is None:
        cells = raw.split()
        assert len(cells) == 0xE0
        t = _TABLES[id(raw)] = (raw, tuple(None if c == "-" else chr(int(c, 16)) for c in cells))
    return t


def known(font: str | None) -> bool:
    """対応表のある記号の書体の名前か。"""
    return key(font) in _NAMES


def is_symbol(font: str | None, symbols=()) -> bool:
    """記号の書体か：対応表のある書体か、文書が記号の書体と宣言した書体（symbols）。"""
    k = key(font)
    return k in _NAMES or (bool(k) and k in symbols)


def _code(ch: str) -> int | None:
    o = ord(ch)
    if 0xF020 <= o <= 0xF0FF:
        return o - 0xF000
    return o if 0x20 <= o <= 0xFF else None


def decode(font: str | None, code: int, symbols=()) -> str:
    """書体 font の番号 code（0x20〜0xFF か U+F020〜U+F0FF）の字。

    対応表のある書体：表の字。表にない番号と、対応表のない記号の書体（symbols）の番号は、私用の領域の字（U+F0xx）。
    記号の書体でない書体：code の字のまま。"""
    if code < 0x20:
        return ""
    t = _table(font, symbols)
    c = code - 0xF000 if 0xF000 <= code <= 0xF0FF else code
    if t is None or not 0x20 <= c <= 0xFF:
        return chr(code)
    return t[1][c - 0x20] or chr(0xF000 + c)


def text(s: str, font: str | None, high_font: str | None = None, symbols=()) -> str:
    """書体 font で書いた字の並び s を、Unicode の字にする（字の数は変わらない）。記号の書体でない書体の字は、そのまま。

    私用の領域の字（U+F020〜U+F0FF）と、U+0021〜U+00FF の字（記号の書体は、この番号の字も記号の形で描く）を読む。
    high_font を渡すと、U+0080〜U+00FF の字はその書体で読む（Word は、字の範囲ごとに書体を持つ）。私用の領域の字は、
    font が記号の書体ならその書体、そうでなければ high_font。空白（U+0020・U+00A0）は空白のまま。
    対応表にない番号と、対応表のない記号の書体（symbols：文書が記号の書体と宣言した書体）の字は、私用の領域の字（U+F0xx）。"""
    low = _table(font, symbols)
    high = low if high_font is None else _table(high_font, symbols)
    if low is None and high is None:
        return s
    out = []
    for ch in s:
        c = _code(ch)
        if c is None or ch in " \xa0":
            out.append(ch)
            continue
        t = (low or high) if ord(ch) >= 0xF000 else low if c < 0x80 else high
        out.append(ch if t is None else t[1][c - 0x20] or chr(0xF000 + c))
    return "".join(out)


@functools.lru_cache(maxsize=64)
def _codes(k: str) -> dict:
    t = _table(k)
    out: dict = {}
    for i, ch in enumerate(t[1] if t else ()):
        # 番号 0x80〜0x9F は入れない：保存する字（U+0080〜U+009F か、Windows の文字コード表の字か）がアプリで違う。
        # 0x20・0xA0 も入れない：その番号の字（空白）は、空白のまま読む（text）
        c = 0x20 + i
        if ch is not None and c not in (0x20, 0xA0) and not 0x80 <= c <= 0x9F:
            out.setdefault(ch, c)
    return out


def code_of(font: str | None, ch: str) -> int | None:
    """書体 font で字 ch を描く番号（0x21〜0x7F・0xA1〜0xFF。同じ字がいくつもあれば小さい番号）。その字のない書体・表のない書体は None。"""
    return _codes(key(font)).get(ch)


def box_codes(font: str | None) -> tuple[int, int] | None:
    """書体 font の、（印のついた箱の番号, 印のない箱の番号）。その字のない書体・表のない書体は None。"""
    t = _table(font)
    return _BOX_CODES.get(id(t[0])) if t else None
