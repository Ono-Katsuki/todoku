# どの文字の種類にも決まらない字（UAX #24）：Common（数字・句読点・記号・µ・ʼ など、いくつもの文字で使う字）、
# Inherited（結合の記号 U+0301 など：前の字の種類を受け継ぐ）、Unknown（まだ字の割り当てのない符号位置）
NEUTRAL_SCRIPTS = frozenset({"Common", "Inherited", "Unknown"})


def script_of(ch: str) -> str:
    """字の文字の種類（Scripts.txt の Script の値：「Latin」「Han」「Devanagari」「Common」「Inherited」など）。
    表にない符号位置は「Unknown」。"""
    c = ord(ch)
    i = bisect.bisect_right(_SCRIPT_STARTS, c) - 1
    if i >= 0 and _SCRIPTS[i][0] <= c <= _SCRIPTS[i][1]:
        return SCRIPT_NAMES[_SCRIPTS[i][2]]
    return "Unknown"
