"""字の種類（どの言語の書類にも同じに使う、Unicode の資料で決まる字の集まり）。

窓の「書き込む所」は、字の意味（「年」「様」などの語）からは決めず、字の形・並び（空白の並び・下線の字の並び・
点線・かっこの組・箱の字）だけで示す。ここに、その字の集まりを、出典つきで1か所にまとめる。

動いている Python の unicodedata から読む性質（表を持たない。版は unicodedata.unidata_version：UCD_VERSION）：
- 空白：一般カテゴリ Zs（U+0020・U+00A0・U+2000〜U+200A・U+3000 など）
- 下線の字：一般カテゴリ Pc（connector punctuation：_ ‿ ⁀ ⁔ ︳ ︴ ﹍ ﹎ ﹏ ＿）
- ダッシュ：一般カテゴリ Pd（dash punctuation：- ‐ – — ― － など）
- 東アジアの字の幅：UAX #11 の East_Asian_Width（W・F は全角）
- 見出しのコロン：一般カテゴリ Po で、名前に語 COLON を含む字（: ： ﹕ ︓ ፥ ᠄ ܃ など）。
  U+061B ؛（ARABIC SEMICOLON）はセミコロン、U+0589 ։（ARMENIAN FULL STOP）は文の終わりの字で、どちらもコロンではない
- 点線（リーダー）の字数：UnicodeData.txt の互換分解（NFKD）で、点の字（FULL STOP）がいくつになるか（「…」U+2026 は「...」）

unicodedata にない資料は、下の表に持つ（scripts/make_chars.py が作る。版は TABLES_UCD_VERSION。Python の版と結びつけない）：
- かっこの組：BidiBrackets.txt（Bidi_Paired_Bracket）
- 文の終わりの字・文や句の区切りの字：PropList.txt の Sentence_Terminal・Terminal_Punctuation
- 字の文字の種類：Scripts.txt の Script（script_of。Common・Inherited は、どの文字の種類にも決まらない字）

箱の字（□・☐ など）：印刷された箱の字は、記入の箱のことも、箇条・見出しの印のこともあり、字（の Unicode の性質）からは決まらない。
どの箱の字も「チェックの欄」とは決めず、「？」の所（規則では決められない所）として、字とその Unicode の名前（glyph_facts）を示す。
チェックの欄と決めるのは、ファイルがそう宣言しているとき（フォームの部品・コンテンツ コントロール・入力規則・つながったセル）だけ。
"""

from __future__ import annotations

import bisect
import functools
import unicodedata

UCD_VERSION = unicodedata.unidata_version  # unicodedata から読む性質の版（動いている Python のもの）


def is_space(ch: str) -> bool:
    """空白（一般カテゴリ Zs）。"""
    return unicodedata.category(ch) == "Zs"


def is_connector(ch: str) -> bool:
    """下線の字（一般カテゴリ Pc）。"""
    return unicodedata.category(ch) == "Pc"


def is_dash(ch: str) -> bool:
    """ダッシュ（一般カテゴリ Pd）。"""
    return unicodedata.category(ch) == "Pd"


# 点線（リーダー）に使う字。Unicode の名前（unicodedata.name）で選んだもの：
#   U+002E FULL STOP・U+FF0E FULLWIDTH FULL STOP・U+00B7 MIDDLE DOT・U+2024 ONE DOT LEADER・U+2025 TWO DOT LEADER・
#   U+2026 HORIZONTAL ELLIPSIS・U+22EF MIDLINE HORIZONTAL ELLIPSIS・U+2E31 WORD SEPARATOR MIDDLE DOT・
#   U+30FB KATAKANA MIDDLE DOT・U+FF65 HALFWIDTH KATAKANA MIDDLE DOT・U+1801 MONGOLIAN ELLIPSIS・
#   U+FE19 PRESENTATION FORM FOR VERTICAL HORIZONTAL ELLIPSIS・U+FE30 PRESENTATION FORM FOR VERTICAL TWO DOT LEADER
LEADERS = frozenset(".．·․‥…⋯⸱・･᠁︙︰")
# 1 字で 2 つ以上の点を表す字（名前に ELLIPSIS・TWO DOT LEADER を含む字：「…」「‥」）
MULTI_DOT = frozenset(ch for ch in LEADERS if "ELLIPSIS" in unicodedata.name(ch) or "TWO DOT" in unicodedata.name(ch))
# 点線の字数の基準：U+2026 HORIZONTAL ELLIPSIS の互換分解（UnicodeData.txt：<compat> 002E 002E 002E）の点の数。
# 点線（リーダー）の並びは、省略の記号 1 つ（「…」＝点 3 つ）以上の点のもの
ELLIPSIS_DOTS = len(unicodedata.normalize("NFKD", "\u2026"))


def dots(ch: str) -> int:
    """点線の字 ch が表す点の数：互換分解（NFKD）の字数（「…」は 3、「‥」は 2）。名前に ELLIPSIS を含み分解のない字
    （U+22EF・U+1801）は「…」と同じ 3、TWO DOT LEADER の縦書きの形（U+FE30）は分解のとおり 2。"""
    n = len(unicodedata.normalize("NFKD", ch))
    if n == 1 and "ELLIPSIS" in unicodedata.name(ch, ""):
        return ELLIPSIS_DOTS
    return n


# 箱の字（Unicode の名前の表 NamesList.txt・ブロック Blocks.txt）。どれも、字からは「記入の箱」とは決まらない：
#   U+2610 BALLOT BOX（Miscellaneous Symbols）・U+25A1 WHITE SQUARE・U+25A2 WHITE SQUARE WITH ROUNDED CORNERS・
#   U+25FB WHITE MEDIUM SQUARE・U+25FD WHITE MEDIUM SMALL SQUARE（Geometric Shapes）・U+2B1C WHITE LARGE SQUARE
#   （Miscellaneous Symbols and Arrows）・U+274F〜U+2752 の影つきの白い四角（Dingbats）
EMPTY_BOXES = frozenset("☐□▢⬜❏❐❑❒◻◽")
# 印のついた箱：U+2611 BALLOT BOX WITH CHECK・U+2612 BALLOT BOX WITH X
CHECKED_BOXES = frozenset("☑☒")
BOXES = EMPTY_BOXES | CHECKED_BOXES
# 印のついた箱かもしれない字：U+25A0 BLACK SQUARE は箇条の印・飾りのことも、U+2713/U+2714 CHECK MARK は本文の印のことも、
# U+25A3 WHITE SQUARE CONTAINING BLACK SMALL SQUARE は記入済みの箱のことも（日本・韓国の様式）、箇条の印・見出しの印の
# ことも（韓国の公文書の「▣」など）ある。どれも、元の字のまま示す
MAYBE_CHECKED = frozenset("■✓✔▣")
# 互換のための名前（ほかの形式の窓が使う）：字からチェックの欄と決まる箱の字はない（空）。印のない箱の字は、どれも
# 箇条・見出しの印のこともある字として「？」にする（BULLET_LIKE_BOXES は EMPTY_BOXES と同じ）
CERTAIN_EMPTY_BOXES: frozenset[str] = frozenset()
BULLET_LIKE_BOXES = EMPTY_BOXES


def is_bullet_like_box(ch: str) -> bool:
    """印のない箱の字か（どれも箇条・見出しの印のこともある：規則のチェックの欄にせず「？」にする字）。"""
    return ch in EMPTY_BOXES


def glyph_facts(ch: str) -> dict:
    """字の事実（窓に添える）：字・符号位置・Unicode の名前・一般カテゴリ・東アジアの字の幅（UAX #11）。"""
    return {"char": ch, "code": f"U+{ord(ch):04X}", "name": unicodedata.name(ch, ""),
            "category": unicodedata.category(ch), "east_asian_width": unicodedata.east_asian_width(ch)}


def is_wide(ch: str) -> bool:
    """東アジアの字の幅（UAX #11）が W（全角）か F（全角の互換用の字）。"""
    return unicodedata.east_asian_width(ch) in ("W", "F")


def width_em(text: str) -> float:
    """字の並びの幅の目安（em）：全角（UAX #11 の W・F。U+3000 の幅は Unicode 第 6 章 6.2 で 1 em）は 1、ほかは 0.5
    （UAX #11 の狭い字：東アジアの組版での半角）。比例する書体では、実際の幅はこれと違う。"""
    return sum(1.0 if is_wide(ch) else 0.5 for ch in text)


def closing(ch: str) -> str | None:
    """開きかっこ ch と対になる閉じかっこ（BidiBrackets.txt）。かっこでなければ None。"""
    return BRACKET_PAIRS.get(ch)


def _in(ranges, starts, ch: str) -> bool:
    c = ord(ch)
    i = bisect.bisect_right(starts, c) - 1
    return i >= 0 and ranges[i][0] <= c <= ranges[i][1]


def is_sentence_terminal(ch: str) -> bool:
    """文の終わりの字（PropList.txt の Sentence_Terminal：。 . ! ? । ۔ ؟ ። ։ など）。"""
    return _in(SENTENCE_TERMINAL_RANGES, _TERM_STARTS, ch)


def is_terminal_punctuation(ch: str) -> bool:
    """文・句の区切りの字（PropList.txt の Terminal_Punctuation：文の終わりの字に、読点・コロン・セミコロンを足したもの）。"""
    return _in(TERMINAL_PUNCTUATION_RANGES, _TP_STARTS, ch)


@functools.lru_cache(maxsize=4096)
def is_label_colon(ch: str) -> bool:
    """見出しのあとのコロン（一般カテゴリ Po で、名前に語 COLON を含む字。SEMICOLON は含めない）。unicodedata から読む。"""
    if len(ch) != 1 or unicodedata.category(ch) != "Po":
        return False
    return "COLON" in unicodedata.name(ch, "").split()


def __getattr__(name: str):
    # LABEL_COLONS：見出しのコロンの字のすべて（初めて使うときに、unicodedata の字を 1 度だけ調べて作る）
    if name == "LABEL_COLONS":
        got = frozenset(chr(c) for c in range(0x110000) if is_label_colon(chr(c)))
        globals()[name] = got
        return got
    raise AttributeError(name)


def char_runs(text: str) -> list[tuple[int, int, str]]:
    """同じ種類の字の並び：(始め, 終わり, 種類)。種類は "space"（Zs）・"connector"（Pc）・"leader"（点線の字）・
    "dash"（Pd）。ほかの字は出さない。"""
    out: list[tuple[int, int, str]] = []
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        kind = ("space" if is_space(ch) else "connector" if is_connector(ch) else "leader" if ch in LEADERS
                else "dash" if is_dash(ch) else None)
        if kind is None:
            i += 1
            continue
        j = i + 1
        while j < n:
            c2 = text[j]
            k2 = ("space" if is_space(c2) else "connector" if is_connector(c2) else "leader" if c2 in LEADERS
                  else "dash" if is_dash(c2) else None)
            if k2 != kind:
                break
            j += 1
        out.append((i, j, kind))
        i = j
    return out


def dot_run(text: str, a: int, b: int) -> bool:
    """text[a:b]（点線の字の並び）が、点線と読める長さか：表す点の数（dots）が、省略の記号「…」1 つ（ELLIPSIS_DOTS＝3）以上。
    「...」「…」「‥‥」は点線、「.」「..」「‥」は句読点・小数点・略語の点のこともある並び。"""
    return sum(dots(ch) for ch in text[a:b]) >= ELLIPSIS_DOTS


